"""
🐳 分辨率选择器节点
功能：支持预设分辨率和自定义分辨率两种模式，统一管理AI绘画的图像分辨率输出
"""


class ResolutionSelectorNode:
    """
    🐳 分辨率选择器节点
    
    这是一个纯参数配置型工具节点，提供两种模式：
    1. 预设分辨率模式：从下拉列表选择标准分辨率
    2. 自定义分辨率模式：手动输入宽度和高度
    
    最终输出标准的整数宽高值给下游节点使用
    """
    
    # ========== 节点元数据 ==========
    
    # 节点在ComfyUI中的分类，会显示在节点列表的哪个分类下
    CATEGORY = "🐳 WP_Node"

    # 输出端口的数据类型，这里是两个整数（宽度和高度）
    RETURN_TYPES = ("INT", "INT")

    # 输出端口的显示名称 - 已汉化
    RETURN_NAMES = ("宽度", "高度")

    # 节点执行时调用的方法名
    FUNCTION = "get_resolution"

    # 标记这是一个输出节点（虽然不需要，但保持和其他节点一致）
    OUTPUT_NODE = True
    
    @classmethod
    def INPUT_TYPES(cls):
        """
        定义节点的输入控件
        
        返回一个字典，描述所有输入参数的类型和选项
        """
        # 预设分辨率列表，每个选项格式为"宽×高 (比例) (横竖屏)"
        # 共27个预设，覆盖常用的AI绘画分辨率
        resolution_presets = [
            "480×832 (3:5.2) (竖屏)",
            "480×854 (9:16) (竖屏)",
            "512×512 (1:1) (方形)",
            "512×768 (2:3) (竖屏)",
            "640×960 (2:3) (竖屏)",
            "768×512 (3:2) (横屏)",
            "768×768 (1:1) (方形)",
            "768×1344 (4:7) (竖屏)",
            "832×480 (5.2:3) (横屏)",
            "832×1216 (13:19) (竖屏)",
            "854×480 (16:9) (横屏)",
            "896×512 (7:4) (横屏)",
            "896×1152 (7:9) (竖屏)",
            "960×640 (3:2) (横屏)",
            "512×896 (4:7) (竖屏)",
            "1024×1024 (1:1) (方形)",
            "1024×1536 (2:3) (竖屏)",
            "1080×1920 (9:16) (竖屏)",
            "1152×896 (9:7) (横屏)",
            "1216×832 (19:13) (横屏)",
            "1280×720 (16:9) (横屏)",
            "720×1280 (9:16) (竖屏)",
            "1344×768 (7:4) (横屏)",
            "1536×1024 (3:2) (横屏)",
            "1920×1080 (16:9) (横屏)",
            "2048×3072 (竖屏)",
            "3072×2048 (横屏)",
        ]
        
        return {
            "required": {
                # 开关控件：切换预设模式和自定义模式
                # True = 使用自定义分辨率，False = 使用预设分辨率
                "使用自定义分辨率": ("BOOLEAN", {
                    "default": False,  # 默认关闭，使用预设分辨率
                    "label_on": "开启",  # 开关打开时显示的文字
                    "label_off": "关闭",  # 开关关闭时显示的文字
                }),
                
                # 下拉选择框：预设分辨率列表
                # 仅在 使用自定义分辨率 = False 时有效
                "预设分辨率": (resolution_presets, {
                    "default": resolution_presets[15],  # 默认选择 1024×1024 (1:1) (方形)
                }),
                
                # 整数输入框：自定义宽度
                # 仅在 使用自定义分辨率 = True 时有效
                "自定义宽度": ("INT", {
                    "default": 1024,     # 默认值
                    "min": 64,           # 最小值
                    "max": 8192,         # 最大值
                    "step": 64,          # 步长（每次增减64）
                    "display": "number", # 显示为数字输入框
                }),
                
                # 整数输入框：自定义高度
                # 仅在 使用自定义分辨率 = True 时有效
                "自定义高度": ("INT", {
                    "default": 1024,     # 默认值
                    "min": 64,           # 最小值
                    "max": 8192,         # 最大值
                    "step": 64,          # 步长（每次增减64）
                    "display": "number", # 显示为数字输入框
                }),
            }
        }
    
    def get_resolution(self, 使用自定义分辨率, 预设分辨率, 自定义宽度, 自定义高度):
        """
        核心处理方法：根据开关状态返回对应的宽高值
        
        参数说明：
            使用自定义分辨率: 布尔值，是否使用自定义分辨率
            预设分辨率: 字符串，预设分辨率选项（如"1024×1024 (1:1) (方形)"）
            自定义宽度: 整数，自定义宽度
            自定义高度: 整数，自定义高度
        
        返回：
            (宽度, 高度): 元组，包含两个整数
        """
        
        # ========== 自定义分辨率模式 ==========
        if 使用自定义分辨率:
            # 当开关开启时，直接使用用户输入的自定义宽高
            # 由于ComfyUI的INT类型已经限制了范围，这里不需要额外检查
            输出宽度 = 自定义宽度
            输出高度 = 自定义高度
            
            # 打印日志，方便调试
            print(f"[分辨率选择器] 使用自定义分辨率: {输出宽度}×{输出高度}")
        
        # ========== 预设分辨率模式 ==========
        else:
            # 当开关关闭时，从预设字符串中解析出宽高数值
            # 预设格式示例："1024×1024 (1:1) (方形)"
            
            try:
                # 第一步：按"×"分割字符串，得到 ["1024", "1024 (1:1) (方形)"]
                部分列表 = 预设分辨率.split("×")
                
                # 提取宽度：第一个部分直接就是宽度
                宽度字符串 = 部分列表[0].strip()  # strip() 去除首尾空格
                
                # 提取高度：第二个部分按空格分割，取第一个元素
                # "1024 (1:1) (方形)" 按空格分割得到 ["1024", "(1:1)", "(方形)"]
                高度字符串 = 部分列表[1].split(" ")[0].strip()
                
                # 转换为整数
                输出宽度 = int(宽度字符串)
                输出高度 = int(高度字符串)
                
                print(f"[分辨率选择器] 使用预设分辨率: {输出宽度}×{输出高度}")
                
            except (IndexError, ValueError) as 错误:
                # 如果解析失败，输出错误信息并返回默认值
                print(f"[分辨率选择器] 解析预设分辨率失败: {预设分辨率}, 错误: {错误}")
                # 使用安全的默认值
                输出宽度 = 1024
                输出高度 = 1024
        
        # 返回最终的宽高值（必须是整数）
        return (输出宽度, 输出高度)
    
    @classmethod
    def IS_CHANGED(cls, 使用自定义分辨率, 预设分辨率, 自定义宽度, 自定义高度):
        """
        检测节点的输入是否发生变化
        
        ComfyUI使用这个方法来决定是否需要重新执行节点
        返回一个能唯一标识当前状态的值
        
        参数和get_resolution相同
        """
        if 使用自定义分辨率:
            # 自定义模式下，根据宽高值判断
            return f"自定义_{自定义宽度}_{自定义高度}"
        else:
            # 预设模式下，根据选中的预设字符串判断
            return f"预设_{预设分辨率}"
