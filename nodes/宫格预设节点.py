"""
🐳 宫格预设节点
功能：生成宫格（网格）预设图，用于故事板或多图对比排版
"""

import torch


class GonggePresetNode:
    """
    🐳 宫格预设节点

    通过下拉框选择预设的宫格布局，自动生成对应尺寸的网格图。
    支持 16:9 宽屏、21:9 宽屏、9:16 竖屏三种比例，每种比例各有 4/6/9 宫格可选。
    格子区域为深灰色，边框为白色，可反转颜色。
    """

    CATEGORY = "🐳 WP_Node"
    RETURN_TYPES = ("IMAGE",)
    RETURN_NAMES = ("IMAGE",)
    FUNCTION = "生成宫格"

    # 预设参数映射表
    预设参数 = {
        "16:9 宽屏-4宫格":  {"宽度": 2048, "高度": 1152, "列数": 2, "行数": 2},
        "16:9 宽屏-6宫格":  {"宽度": 3072, "高度": 1152, "列数": 3, "行数": 2},
        "16:9 宽屏-9宫格":  {"宽度": 3072, "高度": 1728, "列数": 3, "行数": 3},
        "21:9 宽屏-4宫格":  {"宽度": 2048, "高度": 878,  "列数": 2, "行数": 2},
        "21:9 宽屏-6宫格":  {"宽度": 3072, "高度": 878,  "列数": 3, "行数": 2},
        "21:9 宽屏-9宫格":  {"宽度": 3072, "高度": 1317, "列数": 3, "行数": 3},
        "9:16 竖屏-4宫格":  {"宽度": 1152, "高度": 2048, "列数": 2, "行数": 2},
        "9:16 竖屏-6宫格":  {"宽度": 1728, "高度": 2048, "列数": 3, "行数": 2},
        "9:16 竖屏-9宫格":  {"宽度": 1728, "高度": 3072, "列数": 3, "行数": 3},
    }

    @classmethod
    def INPUT_TYPES(cls):
        预设列表 = list(cls.预设参数.keys())

        return {
            "required": {
                "预设布局": (预设列表, {
                    "default": 预设列表[0],
                }),
                "反转颜色": ("BOOLEAN", {
                    "default": False,
                }),
            }
        }

    def 生成宫格(self, 预设布局, 反转颜色):
        """
        根据预设布局生成宫格网格图

        参数说明：
            预设布局: 字符串，如"16:9 宽屏-4宫格"
            反转颜色: 布尔值，是否黑白反转

        返回：
            (图片张量,): 包含一张宫格图片的元组
        """
        # 固定参数
        边框粗细 = 4
        背景灰度值 = 25

        参数 = self.预设参数.get(预设布局)
        if 参数 is None:
            参数 = list(self.预设参数.values())[0]

        宽度 = 参数["宽度"]
        高度 = 参数["高度"]
        列数 = 参数["列数"]
        行数 = 参数["行数"]
        格子数量 = 列数 * 行数

        # 创建全白画布（1.0 = 白色）
        网格图 = torch.ones((高度, 宽度), dtype=torch.float32)

        背景浮点值 = 背景灰度值 / 255.0
        每格宽度 = 宽度 / 列数
        每格高度 = 高度 / 行数
        半边框 = 边框粗细 / 2

        # 逐个画出格子区域（涂成0，后续替换为背景色）
        for 行 in range(行数):
            for 列 in range(列数):
                格子索引 = 行 * 列数 + 列
                if 格子索引 >= 格子数量:
                    continue

                左边界 = int(round(列 * 每格宽度 + 半边框))
                上边界 = int(round(行 * 每格高度 + 半边框))
                右边界 = int(round((列 + 1) * 每格宽度 - 半边框))
                下边界 = int(round((行 + 1) * 每格高度 - 半边框))

                # 边缘格子延伸到边界（不留外边框）
                if 列 == 0:
                    左边界 = 0
                if 行 == 0:
                    上边界 = 0
                if 列 == 列数 - 1:
                    右边界 = 宽度
                if 行 == 行数 - 1:
                    下边界 = 高度

                网格图[上边界:下边界, 左边界:右边界] = 0.0

        # 将格子区域替换为背景色，边框保留白色
        最终网格 = torch.where(
            网格图 == 1.0,
            torch.tensor(1.0, dtype=torch.float32),
            torch.tensor(背景浮点值, dtype=torch.float32)
        )

        if 反转颜色:
            最终网格 = 1.0 - 最终网格

        # 转换为 RGB 三通道
        RGB张量 = 最终网格.unsqueeze(-1).repeat(1, 1, 3)

        # 输出格式：batch × H × W × C
        输出图片 = RGB张量.unsqueeze(0)

        return (输出图片,)


